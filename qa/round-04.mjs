import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
const task = await taskSpace(2);
const page = task.page('p2');
await page.click('#load-sources');
await page.waitForFunction(() => document.getElementById('source-count').textContent === '3' && document.getElementById('activity').hidden);
await page.click('#extract-sources');
await page.waitForFunction(() => document.querySelectorAll('.status.done').length === 2 && document.getElementById('activity').hidden);
assert.equal(await page.evaluate(() => document.querySelectorAll('.status.error').length), 1);
const downloadPromise = page.waitForEvent('download', { timeout: 15000 });
await page.click('#download-markdown');
const download = await downloadPromise;
await download.saveAs('D:/Code/Projects/youtube_search/research-helper/qa/partial-export.md');
const markdown = await readFile('D:/Code/Projects/youtube_search/research-helper/qa/partial-export.md', 'utf8');
assert.match(markdown, /추출하지 못한 소스/);
assert.match(markdown, /\n\n2026\n\n/);
await page.evaluate(() => { window.__qa.failSource = false; });
const beforeRetry = await page.evaluate(() => window.__qa.calls.filter(c => c.args[0].operation === 'text').length);
await page.click('#extract-sources');
await page.waitForFunction(() => document.querySelectorAll('.status.done').length === 3 && document.getElementById('activity').hidden);
const afterRetry = await page.evaluate(() => window.__qa.calls.filter(c => c.args[0].operation === 'text').length);
assert.equal(afterRetry - beforeRetry, 1);
console.log({ partialExportBytes: Buffer.byteLength(markdown), retriedOnlyFailedSource: afterRetry - beforeRetry, completedSources: 3 });
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'D:/Code/Projects/youtube_search/research-helper/qa/sources-preview.png' });
console.log(await page.snapshot({ scope: 'full_page' }));
