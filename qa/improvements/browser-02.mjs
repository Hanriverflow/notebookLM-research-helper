import assert from 'node:assert/strict';
const task = await taskSpace(5);
const page = task.page('p1');
await page.click('details.manual > summary');
await page.fill('#manual-urls', 'https://youtu.be/abcdefghijk');
await page.click('#add-urls');
await page.waitForFunction(() => document.getElementById('video-count').textContent === '1');
await page.click('#collect-videos');
await page.waitForFunction(() => document.getElementById('activity').hidden && document.getElementById('video-count').textContent === '3');
const title = await page.evaluate(() => document.querySelector('#video-list .item-title').textContent);
assert.equal(title, 'https://www.youtube.com/watch?v=abcdefghijk');
console.log({ baselineMetadataBug: true, title });
await page.click('#send-notebook');
await page.click('#load-sources');
await page.waitForFunction(() => document.getElementById('source-count').textContent === '3' && document.getElementById('activity').hidden);
await page.evaluate(() => { window.__qa.failSource = false; });
await page.click('#extract-sources');
await page.waitForFunction(() => document.querySelectorAll('.status.done').length === 3 && document.getElementById('activity').hidden);
const before = await page.evaluate(() => window.__qa.calls.filter(call => call.args[0].operation === 'text').length);
await page.click('#load-sources');
await page.waitForFunction(() => document.getElementById('activity').hidden);
await page.click('#extract-sources');
await page.waitForFunction(() => document.getElementById('notice').textContent.includes('모두 추출'));
const after = await page.evaluate(() => window.__qa.calls.filter(call => call.args[0].operation === 'text').length);
assert.equal(after, before);
console.log({ baselineRefreshBug: true, before, after });
await page.screenshot({ path: 'D:/Code/Projects/youtube_search/research-helper/qa/improvements/baseline.png' });
console.log(await page.snapshot({ scope: 'full_page' }));
